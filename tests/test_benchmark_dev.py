"""Automated satisfiability gate test suite for FLBDS v9 §5.1 / §6.3.

Principle P10:
1. Pre-admission capacity bound check on all 12 dev cases.
2. Strict schema validation: Problem Cards contain zero template leakage.
3. Every reference design is solver-generated and 100% passes M5-Eval.
4. GroundTruthEval contains acceptable_templates list and expected operators.
"""

import json
from pathlib import Path
import pytest
from pydantic import TypeAdapter

from flbds.schema.enums import BoundaryTypeEnum, TemplateEnum
from flbds.schema.ground_truth_eval import GroundTruthEval
from flbds.schema.problem_card import ProblemCard
from flbds.schema.templates import (
    TemplateParameters,
    TPL02Params,
    TPL08Params,
    TPL09Params,
    TPL10Params,
)
from flbds.physics.capacity_bound import check_problem_satisfiability
from flbds.physics.tpl02_pcm import eval_tpl02
from flbds.physics.tpl08_countercurrent import eval_tpl08
from flbds.physics.tpl09_radiative import eval_tpl09
from flbds.physics.tpl10_diffusion import eval_tpl10

DEV_DIR = Path("flbds/benchmark/dev")
CASE_IDS = [
    "DEV-M1-S1", "DEV-M1-S2", "DEV-M1-S3",
    "DEV-M2-S1", "DEV-M2-S2", "DEV-M2-S3",
    "DEV-M3-S1", "DEV-M3-S2", "DEV-M3-S3",
    "DEV-M4-S1", "DEV-M4-S2", "DEV-M4-S3",
]


class TestBenchmarkDevSatisfiability:
    """Verifies that all 12 dev cases pass the automated satisfiability gate."""

    @pytest.mark.parametrize("case_id", CASE_IDS)
    def test_case_files_exist_and_conform_to_schema(self, case_id: str):
        case_dir = DEV_DIR / case_id
        assert case_dir.is_dir(), f"Case directory missing: {case_dir}"

        prob_file = case_dir / "problem_card.json"
        gt_file = case_dir / "ground_truth_eval.json"
        ref_file = case_dir / "reference_design.json"

        assert prob_file.is_file(), f"problem_card.json missing for {case_id}"
        assert gt_file.is_file(), f"ground_truth_eval.json missing for {case_id}"
        assert ref_file.is_file(), f"reference_design.json missing for {case_id}"

        # 1. Parse and validate ProblemCard (strictly verifies no template leakage)
        with open(prob_file) as f:
            prob = ProblemCard.model_validate_json(f.read())
        assert prob.problem_id.startswith("PROB-DEV-")

        # 2. Parse and validate GroundTruthEval
        with open(gt_file) as f:
            gt = GroundTruthEval.model_validate_json(f.read())
        assert len(gt.acceptable_templates) >= 1
        assert gt.case_id == case_id

        # 3. Parse and validate Reference Design with discriminated union
        adapter = TypeAdapter(TemplateParameters)
        with open(ref_file) as f:
            ref_design = adapter.validate_json(f.read())
        assert ref_design.template_id in [
            t.value if hasattr(t, "value") else str(t) for t in gt.acceptable_templates
        ] or any(ref_design.template_id == t for t in gt.acceptable_templates)

    @pytest.mark.parametrize("case_id", CASE_IDS)
    def test_capacity_bound_satisfiability(self, case_id: str):
        """Principle P10: Pre-admission capacity bound must pass."""
        case_dir = DEV_DIR / case_id
        with open(case_dir / "problem_card.json") as f:
            prob = ProblemCard.model_validate_json(f.read())
        adapter = TypeAdapter(TemplateParameters)
        with open(case_dir / "reference_design.json") as f:
            ref_design = adapter.validate_json(f.read())

        possible, explanation = check_problem_satisfiability(prob, ref_design.template_id, ref_design)
        assert possible, f"Capacity bound violated for {case_id}: {explanation}"

    @pytest.mark.parametrize("case_id", CASE_IDS)
    def test_reference_design_passes_m5_eval(self, case_id: str):
        """Principle P10: Reference design generated by solver must 100% pass M5-Eval."""
        case_dir = DEV_DIR / case_id
        adapter = TypeAdapter(TemplateParameters)
        with open(case_dir / "reference_design.json") as f:
            ref_design = adapter.validate_json(f.read())

        if isinstance(ref_design, TPL02Params):
            check = eval_tpl02(ref_design, bc_type=BoundaryTypeEnum.BC_FLUX)
        elif isinstance(ref_design, TPL08Params):
            check = eval_tpl08(ref_design)
        elif isinstance(ref_design, TPL09Params):
            check = eval_tpl09(ref_design)
        elif isinstance(ref_design, TPL10Params):
            check = eval_tpl10(ref_design)
        else:
            pytest.fail(f"Unhandled template type: {type(ref_design)}")

        assert check.passed, f"Reference design for {case_id} failed M5-Eval: {check.reason}"
